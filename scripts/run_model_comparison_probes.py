def generate_visualizations(all_results, config):
    """Generate summary plots from all results."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.ticker as mticker
    except ImportError:
        print("\n⚠️  matplotlib not installed. Skipping plots.")
        return

    exp_cfg = config["experiment"]
    save_root = exp_cfg["save_root"]
    figures_dir = os.path.join(save_root, "figures")
    os.makedirs(figures_dir, exist_ok=True)

    task = config["task"]
    task_type = config["task_type"]
    metric_name = "AUPRC" if task_type == "multi_label" else "Accuracy"

    # Collect data — prefer test metrics, fall back to val metrics
    def _get_primary_metric(r):
        """Get the primary metric from test set if available, else val."""
        test_m = r.get("test_metrics", {})
        if test_m:
            if task_type == "multi_label":
                return test_m.get("macro_auprc", r["best_val_metric"])
            else:
                return test_m.get("accuracy", r["best_val_metric"])
        return r["best_val_metric"]

    # Build per-model metrics dict (handles missing probe types gracefully)
    model_metrics = {}
    for r in all_results:
        m = r["model"]
        if m not in model_metrics:
            model_metrics[m] = {"cls": None, "patch": None}
        model_metrics[m][r["probe_type"]] = _get_primary_metric(r)

    unique_models = list(model_metrics.keys())
    cls_metrics = [model_metrics[m]["cls"] or 0.0 for m in unique_models]
    patch_metrics = [model_metrics[m]["patch"] or 0.0 for m in unique_models]

    # --- Plot 1: Grouped bar chart comparing models ---
    fig, ax = plt.subplots(figsize=(10, 6))
    x = np.arange(len(unique_models))
    width = 0.35

    bars1 = ax.bar(x - width/2, cls_metrics, width, label="CLS Probe",
                   color="#2196F3", edgecolor="white")
    bars2 = ax.bar(x + width/2, patch_metrics, width, label="Patch Probe",
                   color="#FF9800", edgecolor="white")

    for bar, val in zip(bars1, cls_metrics):
        ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 0.01,
                f"{val:.4f}", ha="center", va="bottom", fontsize=9)
    for bar, val in zip(bars2, patch_metrics):
        ax.text(bar.get_x() + bar.get_width()/2, bar.get_height() + 0.01,
                f"{val:.4f}", ha="center", va="bottom", fontsize=9)

    ax.set_xticks(x)
    ax.set_xticklabels([m.replace("_", "-").upper() for m in unique_models], fontsize=11)
    ax.set_ylabel(f"Test {metric_name}")
    ax.set_title(f"Model Comparison Study: {task.upper()} — Test {metric_name} by Model and Probe Type")
    ax.legend(fontsize=10)
    all_metrics = [v for v in cls_metrics + patch_metrics if v is not None]
    if all_metrics:
        ax.set_ylim(0, max(all_metrics) * 1.15 + 0.05)
    ax.grid(axis="y", alpha=0.3)
    plt.tight_layout()

    path = os.path.join(figures_dir,f"{task}_comparison_bars.png")
    fig.savefig(path, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"  ✅ Saved: {path}")

    # --- Plot 2: Grid search heatmaps ---
    lrs = [str(lr) for lr in exp_cfg["learning_rates"]]
    probe_types = ["cls", "patch"]

    for probe_type in probe_types:
        matrix = []
        for r in all_results:
            if r["probe_type"] == probe_type:
                row = []
                for lr in lrs:
                    row.append(r["lr_results"].get(lr, {}).get("val_metric", 0.0))
                matrix.append(row)

        if not matrix:
            continue

        matrix = np.array(matrix)
        model_labels = [r["model"] for r in all_results if r["probe_type"] == probe_type]

        fig, ax = plt.subplots(figsize=(max(6, len(lrs) * 1.2),
                                        max(3, len(model_labels) * 0.8)))
        im = ax.imshow(matrix, aspect="auto", cmap="YlOrRd", vmin=0.0)

        ax.set_xticks(range(len(lrs)))
        ax.set_xticklabels(lrs, fontsize=9)
        ax.set_yticks(range(len(model_labels)))
        ax.set_yticklabels([m.replace("_", "-").upper() for m in model_labels], fontsize=9)
        ax.set_xlabel("Learning Rate")
        ax.set_ylabel("Model")

        for i in range(len(model_labels)):
            for j in range(len(lrs)):
                val = matrix[i, j]
                if val > 0:
                    text_color = "white" if val < 0.5 else "black"
                    ax.text(j, i, f"{val:.4f}", ha="center", va="center",
                            fontsize=8, color=text_color, fontweight="bold")

        cbar = fig.colorbar(im, ax=ax, shrink=0.8)
        cbar.set_label(f"Val {metric_name}")
        ax.set_title(f"Grid Search — {probe_type.upper()} Probe ({task.upper()})")
        plt.tight_layout()

        path = os.path.join(figures_dir,f"{task}_{probe_type}_grid_search.png")
        fig.savefig(path, dpi=150, bbox_inches="tight")
        plt.close(fig)
        print(f"  ✅ Saved: {path}")

    # --- Plot 3: Per-class AUPRC heatmap (multi-label tasks, from test set) ---
    # Resolve class names for both ReX and TotalSegmentator
    plot_class_names = config.get("rex_classes", None) or config.get("ts_classes", None)
    if task_type == "multi_label" and plot_class_names:
        for probe_type in probe_types:
            matrix = []
            model_labels = []
            # Collect prevalence info from first model's test metrics
            prevalence_info = None
            for r in all_results:
                if r["probe_type"] == probe_type:
                    model_labels.append(r["model"])
                    # Prefer test per-class metrics, fall back to val
                    test_m = r.get("test_metrics", {})
                    per_class = test_m.get("per_class", {}) if test_m else {}
                    if not per_class:
                        per_class = r.get("val_detailed_metrics", {}).get("per_class", {})
                    if prevalence_info is None:
                        prevalence_info = per_class
                    row = []
                    for cls_name in plot_class_names:
                        row.append(per_class.get(cls_name, {}).get("auprc", 0.0))
                    matrix.append(row)

            if not matrix:
                continue

            matrix = np.array(matrix)

            # Build x-tick labels with prevalence annotation
            x_labels = []
            for j, cls_name in enumerate(plot_class_names):
                if prevalence_info and cls_name in prevalence_info:
                    prev = prevalence_info[cls_name].get("eval_prevalence", None)
                    if prev is not None and prev > 0:
                        x_labels.append(f"{cls_name}\n({prev:.1%})")
                    else:
                        x_labels.append(f"{cls_name}\n(0%)")
                else:
                    x_labels.append(cls_name)

            fig, ax = plt.subplots(figsize=(max(16, len(plot_class_names) * 1.0),
                                             max(5, len(model_labels) * 0.7)))
            im = ax.imshow(matrix, aspect="auto", cmap="YlOrRd", vmin=0.0, vmax=1.0)

            ax.set_xticks(range(len(plot_class_names)))
            ax.set_xticklabels(x_labels, rotation=45, ha="right", fontsize=7)
            ax.set_yticks(range(len(model_labels)))
            ax.set_yticklabels([m.replace("_", "-").upper() for m in model_labels], fontsize=9)

            for i in range(len(model_labels)):
                for j in range(len(plot_class_names)):
                    val = matrix[i, j]
                    if val > 0:
                        text_color = "white" if val < 0.55 else "black"
                        ax.text(j, i, f"{val:.3f}", ha="center", va="center",
                                fontsize=7, color=text_color, fontweight="bold")

            cbar = fig.colorbar(im, ax=ax, shrink=0.8)
            cbar.set_label("AUPRC")
            ax.set_title(f"Test Per-Class AUPRC (with prevalence) — {probe_type.upper()} Probe ({task.upper()})")
            plt.tight_layout()

            path = os.path.join(figures_dir,f"{task}_{probe_type}_per_class_heatmap.png")
            fig.savefig(path, dpi=150, bbox_inches="tight")
            plt.close(fig)
            print(f"  ✅ Saved: {path}")

    # --- Write summary table ---
    summary_path = os.path.join(figures_dir,"summary_table.txt")
    with open(summary_path, "w") as f:
        f.write(f"MODEL COMPARISON STUDY SUMMARY — {task.upper()}\n")
        f.write("=" * 120 + "\n")
        if task_type == "multi_label":
            header = (f"{'Model':<20} {'Probe':<8} {'Best LR':<10} "
                      f"{'Val AUPRC':<12} {'Test AUPRC':<12} "
                      f"{'Valid/Total':<14} {'Skipped':<10}")
        else:
            header = (f"{'Model':<20} {'Probe':<8} {'Best LR':<10} "
                      f"{'Val Acc':<12} {'Test Acc':<12}")
        f.write(header + "\n")
        f.write("-" * 120 + "\n")
        for r in sorted(all_results, key=lambda x: _get_primary_metric(x), reverse=True):
            test_m = r.get("test_metrics", {})
            if task_type == "multi_label":
                test_val = test_m.get("macro_auprc", 0.0)
                n_valid = test_m.get("n_valid_classes", "?")
                n_total = test_m.get("n_total_classes", "?")
                n_skip = test_m.get("n_skipped_classes", "?")
                f.write(
                    f"{r['model']:<20} {r['probe_type']:<8} "
                    f"{str(r['best_lr']):<10} {r['best_val_metric']:<12.4f} "
                    f"{test_val:<12.4f} {n_valid}/{n_total:<11} {n_skip:<10}\n"
                )
            else:
                test_val = test_m.get("accuracy", 0.0)
                f.write(
                    f"{r['model']:<20} {r['probe_type']:<8} "
                    f"{str(r['best_lr']):<10} {r['best_val_metric']:<12.4f} {test_val:<12.4f}\n"
                )
        f.write("=" * 120 + "\n")

        # Add per-class prevalence summary
        if task_type == "multi_label" and plot_class_names:
            f.write("\nPER-CLASS PREVALENCE (from first model's test set)\n")
            f.write("-" * 80 + "\n")
            f.write(f"{'Class':<25} {'Train Prev':<14} {'Val Prev':<14} {'Test Prev':<14} {'#Pos':<8} {'Valid':<8}\n")
            f.write("-" * 80 + "\n")
            # Get prevalence from first result's test metrics
            first_test_m = all_results[0].get("test_metrics", {})
            first_per_class = first_test_m.get("per_class", {})
            for cls_name in plot_class_names:
                info = first_per_class.get(cls_name, {})
                train_p = info.get("train_prevalence")
                val_p = info.get("val_prevalence")
                test_p = info.get("eval_prevalence")
                n_pos = info.get("eval_positive_count", 0)
                valid = "Yes" if info.get("sufficient_data") else "No"
                f.write(
                    f"{cls_name:<25} "
                    f"{train_p if train_p is not None else 'N/A':<14} "
                    f"{val_p if val_p is not None else 'N/A':<14} "
                    f"{test_p if test_p is not None else 'N/A':<14} "
                    f"{n_pos:<8} {valid:<8}\n"
                )
            f.write("-" * 80 + "\n")
    print(f"  ✅ Saved: {summary_path}")


