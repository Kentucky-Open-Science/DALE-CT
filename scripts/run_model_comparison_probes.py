def run_grid_search(model_key, probe_type, config, device):
    """
    Run grid search over learning rates for a single (model, probe_type).

    Uses patient-level train/val/test split. Grid search selects best LR
    on validation set, then evaluates on test set for final reporting.

    Returns:
        results dict with best_lr, best_val_metric, test_metrics, etc.
    """
    exp_cfg = config["experiment"]
    emb_cfg = config["embeddings"]
    gt_cfg = config["groundtruth"]
    task = config["task"]
    task_type = config["task_type"]
    num_classes = config["num_classes"]

    embedding_dir = os.path.join(emb_cfg["root"], model_key, emb_cfg["method"])
    gt_dir = os.path.join(gt_cfg["root"], gt_cfg["task"])
    split_file = os.path.join(gt_cfg["root"], gt_cfg.get("split_file", "patient_splits.json"))

    if not os.path.exists(split_file):
        raise FileNotFoundError(
            f"Patient split file not found: {split_file}. "
            f"Run extract_model_comparison_groundtruth.py first."
        )

    print(f"\n{'=' * 60}")
    print(f"Model: {model_key} | Probe: {probe_type} | Task: {task}")
    print(f"{'=' * 60}")

    # Load data with patient-level splits
    train_X, train_y, val_X, val_y, test_X, test_y = load_embeddings_and_labels(
        embedding_dir, gt_dir, task, model_key, probe_type,
        split_file_path=split_file,
        seed=exp_cfg["seed"]
    )

    # Grid search over LRs using validation set
    best_lr = None
    best_val_metric = -1.0
    best_state_dict = None
    lr_results = {}

    for lr in exp_cfg["learning_rates"]:
        print(f"\n  LR={lr}...")

        if probe_type == "cls":
            model = CLSLinearProbe(exp_cfg["input_dim"], num_classes, task_type)
        else:
            model = PatchLinearProbe(exp_cfg["input_dim"], num_classes, task_type)

        val_metric, state_dict = train_probe(
            model, train_X, train_y, val_X, val_y,
            lr=lr,
            total_steps=exp_cfg["total_steps"],
            eval_freq=exp_cfg["eval_freq"],
            batch_size=exp_cfg["batch_size"],
            task_type=task_type,
            device=device,
        )

        lr_results[str(lr)] = {"val_metric": float(val_metric)}
        print(f"    Val metric: {val_metric:.4f}")

        if val_metric > best_val_metric:
            best_val_metric = val_metric
            best_lr = lr
            best_state_dict = state_dict

    # Save best model
    save_dir = os.path.join(exp_cfg["save_root"], model_key, probe_type)
    os.makedirs(save_dir, exist_ok=True)

    best_model_path = os.path.join(save_dir, "best_model.pth")
    torch.save(best_state_dict, best_model_path)

    # Evaluate best model on validation set with detailed metrics
    if probe_type == "cls":
        best_model = CLSLinearProbe(exp_cfg["input_dim"], num_classes, task_type)
    else:
        best_model = PatchLinearProbe(exp_cfg["input_dim"], num_classes, task_type)
    best_model.load_state_dict(best_state_dict)
    best_model = best_model.to(device)

    val_X_t = torch.from_numpy(val_X).float()
    if task_type == "multi_label":
        val_y_t = torch.from_numpy(val_y).float()
    else:
        val_y_t = torch.from_numpy(val_y).long()

    # Resolve class names: rex_classes for ReX, ts_classes for TotalSegmentator
    class_names = config.get("rex_classes", None) or config.get("ts_classes", None)
    min_pos = exp_cfg.get("min_positive_samples", 5)
    val_detailed = evaluate_probe_detailed(
        best_model, val_X_t, val_y_t,
        batch_size=exp_cfg["batch_size"],
        task_type=task_type,
        device=device,
        class_names=class_names,
        train_y=train_y,
        val_y=val_y,
        min_positive_samples=min_pos,
    )

    # --- Evaluate on test set ---
    test_metrics = {}
    if len(test_X) > 0:
        test_X_t = torch.from_numpy(test_X).float()
        if task_type == "multi_label":
            test_y_t = torch.from_numpy(test_y).float()
        else:
            test_y_t = torch.from_numpy(test_y).long()

        test_metrics = evaluate_probe_detailed(
            best_model, test_X_t, test_y_t,
            batch_size=exp_cfg["batch_size"],
            task_type=task_type,
            device=device,
            class_names=class_names,
            train_y=train_y,
            val_y=val_y,
            min_positive_samples=min_pos,
        )
        print(f"  Test metrics: { {k: v for k, v in test_metrics.items() if k != 'per_class'} }")

    results = {
        "model": model_key,
        "probe_type": probe_type,
        "task": task,
        "best_lr": best_lr,
        "best_val_metric": float(best_val_metric),
        "lr_results": lr_results,
        "val_detailed_metrics": val_detailed,
        "test_metrics": test_metrics,
        "n_train": int(len(train_X)),
        "n_val": int(len(val_X)),
        "n_test": int(len(test_X)),
    }

    # Save results JSON
    results_path = os.path.join(save_dir, "best_metrics.json")
    with open(results_path, "w") as f:
        json.dump(results, f, indent=2, default=str)

    print(f"\n  Best LR: {best_lr}, Best val metric: {best_val_metric:.4f}")
    print(f"  Saved to: {save_dir}")

    return results


