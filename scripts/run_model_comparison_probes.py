def load_config(path):
    """Load YAML config. Tries OmegaConf first, falls back to PyYAML."""
    try:
        from omegaconf import OmegaConf
        return OmegaConf.load(path)
    except ImportError:
        import yaml
        with open(path, "r") as f:
            return yaml.safe_load(f)


