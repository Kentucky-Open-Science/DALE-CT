class CLSLinearProbe(nn.Module):
    """Single linear layer on CLS token for slice-level classification."""

    def __init__(self, input_dim, num_classes, task_type="multi_label"):
        super().__init__()
        self.classifier = nn.Linear(input_dim, num_classes)
        self.task_type = task_type

    def forward(self, x):
        """
        Args:
            x: [B, D] CLS token embeddings
        Returns:
            logits: [B, num_classes]
        """
        return self.classifier(x)


class PatchLinearProbe(nn.Module):
    """Single linear layer applied per-patch for patch-level classification."""

    def __init__(self, input_dim, num_classes, task_type="multi_label"):
        super().__init__()
        self.classifier = nn.Linear(input_dim, num_classes)
        self.task_type = task_type

    def forward(self, x):
        """
        Args:
            x: [B, N_patches, D] patch token embeddings
        Returns:
            logits: [B, N_patches, num_classes]
        """
        return self.classifier(x)


