def train_probe(model, train_X, train_y, val_X, val_y, lr, total_steps,
                eval_freq, batch_size, task_type, device):
    """
    Train a linear probe with SGD and cosine annealing.

    Returns:
        best_val_metric: float (AUPRC for multi_label, accuracy for multi_class)
        best_state_dict: model state dict at best validation metric
    """
    model = model.to(device)

    if task_type == "multi_label":
        criterion = nn.BCEWithLogitsLoss()
        train_y_t = torch.from_numpy(train_y).float()
        val_y_t = torch.from_numpy(val_y).float()
    else:
        criterion = nn.CrossEntropyLoss()
        train_y_t = torch.from_numpy(train_y).long()
        val_y_t = torch.from_numpy(val_y).long()

    train_X_t = torch.from_numpy(train_X).float()
    val_X_t = torch.from_numpy(val_X).float()

    optimizer = optim.SGD(model.parameters(), lr=lr, momentum=0.95, weight_decay=0)
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=total_steps)

    best_val_metric = -1.0
    best_state_dict = {k: v.cpu().clone() for k, v in model.state_dict().items()}

    n_samples = len(train_X_t)

    for step in range(1, total_steps + 1):
        # Sample random batch
        indices = torch.randint(0, n_samples, (batch_size,))
        x_batch = train_X_t[indices].to(device)
        y_batch = train_y_t[indices].to(device)

        optimizer.zero_grad()
        logits = model(x_batch)
        loss = criterion(logits, y_batch)
        loss.backward()
        optimizer.step()
        scheduler.step()

        if step % eval_freq == 0 or step == total_steps:
            val_metric = evaluate_probe(
                model, val_X_t, val_y_t, batch_size, task_type, device
            )
            if val_metric > best_val_metric:
                best_val_metric = val_metric
                best_state_dict = {k: v.cpu().clone() for k, v in model.state_dict().items()}

    return best_val_metric, best_state_dict


@torch.no_grad()
def evaluate_probe(model, X, y, batch_size, task_type, device):
    """Evaluate probe and return the primary metric."""
    model.eval()
    all_probs = []
    n_samples = len(X)

    for i in range(0, n_samples, batch_size):
        x_batch = X[i:i + batch_size].to(device)
        logits = model(x_batch)
        if task_type == "multi_label":
            probs = torch.sigmoid(logits).cpu().numpy()
        else:
            probs = torch.softmax(logits, dim=-1).cpu().numpy()
        all_probs.append(probs)

    probs = np.concatenate(all_probs, axis=0)
    y_np = y.numpy()

    if task_type == "multi_label":
        # Binarize soft labels for sklearn metrics (TotalSegmentator uses
        # fractional coverage labels; BCE loss handles soft labels natively).
        y_bin = (y_np > 0).astype(np.float32)
        try:
            metric = average_precision_score(y_bin, probs, average="macro")
        except ValueError:
            metric = 0.0
    else:
        preds = probs.argmax(axis=1)
        metric = accuracy_score(y_np, preds)

    model.train()
    return metric


@torch.no_grad()
def evaluate_probe_detailed(model, X, y, batch_size, task_type, device,
                             class_names=None, train_y=None, val_y=None,
                             min_positive_samples=5):
    """Evaluate probe and return detailed metrics.

    Args:
        model: The probe model.
        X, y: Evaluation data (test or val).
        batch_size: Batch size for inference.
        task_type: "multi_label" or "multi_class".
        device: Torch device.
        class_names: Optional list of class name strings.
        train_y: Training labels (numpy) for computing prevalence.
        val_y: Validation labels (numpy) for computing prevalence.
        min_positive_samples: Minimum number of positive samples required
            in the evaluation set for a class to be considered "valid"
            for metric reporting. Classes below this threshold get
            metrics set to 0.0 and are flagged as "insufficient_data".

    Returns:
        metrics dict with macro_auroc, macro_auprc, per_class, and
        per_class_prevalence keys.
    """
    model.eval()
    all_probs = []
    n_samples = len(X)

    for i in range(0, n_samples, batch_size):
        x_batch = X[i:i + batch_size].to(device)
        logits = model(x_batch)
        if task_type == "multi_label":
            probs = torch.sigmoid(logits).cpu().numpy()
        else:
            probs = torch.softmax(logits, dim=-1).cpu().numpy()
        all_probs.append(probs)

    probs = np.concatenate(all_probs, axis=0)
    y_np = y.numpy()

    # Binarize soft labels for sklearn metrics (TotalSegmentator uses
    # fractional coverage labels; BCE loss handles soft labels natively).
    if task_type == "multi_label":
        y_eval = (y_np > 0).astype(np.float32)
    else:
        y_eval = y_np

    # --- Compute per-class prevalences ---
    # Prevalence = fraction of samples where the class is present (>0 for
    # multi_label soft labels, >0.5 for binary).
    def _compute_prevalence(labels, num_classes):
        """Compute per-class positive rate from a label matrix."""
        if labels is None or len(labels) == 0:
            return None
        if labels.ndim == 1:
            # Multi-class: count per class
            counts = np.bincount(labels.astype(int), minlength=num_classes)
            return (counts / len(labels)).tolist()
        else:
            # Multi-label: fraction of samples with >0 for each class
            binary = (labels > 0).astype(np.float32)
            return binary.mean(axis=0).tolist()

    num_classes = y_eval.shape[1] if y_eval.ndim > 1 else int(y_eval.max()) + 1
    train_prev = _compute_prevalence(train_y, num_classes)
    val_prev = _compute_prevalence(val_y, num_classes)
    eval_prev = _compute_prevalence(y_np, num_classes)

    # --- Determine which classes have sufficient data ---
    # A class is "valid" if it has >= min_positive_samples positive examples
    # in the evaluation set.
    if y_eval.ndim > 1:
        eval_pos_counts = (y_eval > 0).sum(axis=0)
    else:
        eval_pos_counts = np.bincount(y_eval.astype(int), minlength=num_classes)
    valid_classes = eval_pos_counts >= min_positive_samples

    metrics = {}

    if task_type == "multi_label":
        # --- Filtered macro metrics (only valid classes) ---
        valid_indices = np.where(valid_classes)[0]
        if len(valid_indices) > 0:
            y_valid = y_eval[:, valid_indices]
            p_valid = probs[:, valid_indices]
            try:
                per_class_auroc = roc_auc_score(y_valid, p_valid, average=None)
                metrics["macro_auroc"] = float(np.nanmean(per_class_auroc))
            except ValueError:
                metrics["macro_auroc"] = 0.0
            try:
                metrics["macro_auprc"] = float(average_precision_score(y_valid, p_valid, average="macro"))
            except ValueError:
                metrics["macro_auprc"] = 0.0
            metrics["n_valid_classes"] = int(len(valid_indices))
            metrics["n_total_classes"] = int(num_classes)
            metrics["n_skipped_classes"] = int(num_classes - len(valid_indices))
        else:
            metrics["macro_auroc"] = 0.0
            metrics["macro_auprc"] = 0.0
            metrics["n_valid_classes"] = 0
            metrics["n_total_classes"] = int(num_classes)
            metrics["n_skipped_classes"] = int(num_classes)

        # --- Also compute original (unfiltered) macro for reference ---
        try:
            per_class_auroc_all = roc_auc_score(y_eval, probs, average=None)
            metrics["macro_auroc_unfiltered"] = float(np.nanmean(per_class_auroc_all))
        except ValueError:
            metrics["macro_auroc_unfiltered"] = 0.0
        try:
            metrics["macro_auprc_unfiltered"] = float(average_precision_score(y_eval, probs, average="macro"))
        except ValueError:
            metrics["macro_auprc_unfiltered"] = 0.0

        # Per-class metrics with prevalence and validity flag
        if class_names:
            per_class = {}
            for i, name in enumerate(class_names):
                if i >= y_eval.shape[1]:
                    break
                y_t = y_eval[:, i]
                y_p = probs[:, i]

                entry = {
                    "train_prevalence": train_prev[i] if train_prev else None,
                    "val_prevalence": val_prev[i] if val_prev else None,
                    "eval_prevalence": eval_prev[i] if eval_prev else None,
                    "eval_positive_count": int(eval_pos_counts[i]),
                    "sufficient_data": bool(valid_classes[i]),
                }

                if not valid_classes[i]:
                    entry["auroc"] = 0.0
                    entry["auprc"] = 0.0
                    entry["skipped_reason"] = (
                        f"Only {int(eval_pos_counts[i])} positive samples "
                        f"(need >= {min_positive_samples})"
                    )
                elif len(np.unique(y_t)) < 2:
                    entry["auroc"] = 0.0
                    entry["auprc"] = 0.0
                else:
                    entry["auroc"] = float(roc_auc_score(y_t, y_p))
                    entry["auprc"] = float(average_precision_score(y_t, y_p))

                per_class[name] = entry
            metrics["per_class"] = per_class
    else:
        preds = probs.argmax(axis=1)
        metrics["accuracy"] = float(accuracy_score(y_np, preds))

        # Per-class accuracy with prevalence
        if class_names:
            per_class = {}
            for i, name in enumerate(class_names):
                if i >= probs.shape[1]:
                    break
                mask = y_np == i
                entry = {
                    "train_prevalence": train_prev[i] if train_prev else None,
                    "val_prevalence": val_prev[i] if val_prev else None,
                    "eval_prevalence": eval_prev[i] if eval_prev else None,
                    "eval_count": int(mask.sum()),
                    "sufficient_data": bool(valid_classes[i]),
                }
                if mask.sum() > 0:
                    entry["accuracy"] = float((preds[mask] == i).mean())
                else:
                    entry["accuracy"] = 0.0
                per_class[name] = entry
            metrics["per_class"] = per_class

    model.train()
    return metrics


