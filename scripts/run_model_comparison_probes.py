def main():
    parser = argparse.ArgumentParser(
        description="Run model comparison study: linear probe training + visualization"
    )
    parser.add_argument(
        "--config", type=str, required=True,
        help="Path to linear_probe_model_comparison_{rex,ts}.yaml"
    )
    parser.add_argument(
        "--models", type=str, nargs="*", default=None,
        help="Specific models to run (default: all from config)"
    )
    parser.add_argument(
        "--probe-types", type=str, nargs="*", default=None,
        choices=["cls", "patch"],
        help="Specific probe types to run (default: all from config)"
    )
    parser.add_argument(
        "--skip-existing", action="store_true",
        help="Skip models that already have results"
    )
    args = parser.parse_args()

    config = load_config(args.config)
    exp_cfg = config["experiment"]
    emb_cfg = config["embeddings"]

    models = args.models if args.models else emb_cfg["models"]
    probe_types = args.probe_types if args.probe_types else exp_cfg["probe_types"]

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")
    print(f"Task: {config['task']}")
    print(f"Models: {models}")
    print(f"Probe types: {probe_types}")
    print(f"Learning rates: {exp_cfg['learning_rates']}")

    all_results = []

    for model_key in models:
        for probe_type in probe_types:
            # Check if already done
            save_dir = os.path.join(exp_cfg["save_root"], model_key, probe_type)
            results_path = os.path.join(save_dir, "best_metrics.json")

            if args.skip_existing and os.path.exists(results_path):
                print(f"\n[SKIP] {model_key}/{probe_type} — already has results")
                with open(results_path, "r") as f:
                    all_results.append(json.load(f))
                continue

            try:
                result = run_grid_search(model_key, probe_type, config, device)
                all_results.append(result)
            except Exception as e:
                print(f"\n[ERROR] {model_key}/{probe_type}: {e}")
                import traceback
                traceback.print_exc()

    # --- Save consolidated results JSON ---
    if all_results:
        save_consolidated_results(all_results, config)

    # --- Generate visualizations ---
    if all_results:
        print("\n" + "=" * 60)
        print("Generating visualizations...")
        print("=" * 60)
        generate_visualizations(all_results, config)

    # --- Print summary ---
    print("\n" + "=" * 100)
    print("MODEL COMPARISON STUDY SUMMARY")
    print("=" * 100)
    metric_name = "AUPRC" if config["task_type"] == "multi_label" else "Accuracy"
    header = f"{'Model':<20} {'Probe':<8} {'Best LR':<10} {'Val ' + metric_name:<14} {'Test ' + metric_name:<14}"
    print(header)
    print("-" * 100)
    for r in sorted(all_results, key=lambda x: (
        x.get("test_metrics", {}).get("macro_auprc", 0.0)
        if config["task_type"] == "multi_label"
        else x.get("test_metrics", {}).get("accuracy", 0.0)
    ), reverse=True):
        test_m = r.get("test_metrics", {})
        if config["task_type"] == "multi_label":
            test_val = test_m.get("macro_auprc", 0.0)
        else:
            test_val = test_m.get("accuracy", 0.0)
        print(
            f"{r['model']:<20} {r['probe_type']:<8} "
            f"{str(r['best_lr']):<10} {r['best_val_metric']:<14.4f} {test_val:<14.4f}"
        )
    print("=" * 100)


if __name__ == "__main__":
    main()
