def load_embeddings_and_labels(embedding_dir, gt_dir, task, model_key,
                                probe_type, split_file_path, seed=42):
    """
    Load pre-extracted embeddings and ground truth labels using a
    pre-computed patient-level train/val/test split.

    Args:
        embedding_dir: Path to {root}/{model_key}/{method}/ directory
        gt_dir: Path to {root}/{task}/ directory
        task: "rex" or "totalseg"
        model_key: e.g. "lejepa_0"
        probe_type: "cls" or "patch"
        split_file_path: Path to patient_splits.json (generated by
                         extract_model_comparison_groundtruth.py)
        seed: Random seed (unused; split is pre-determined)

    Returns:
        (train_X, train_y, val_X, val_y, test_X, test_y) as numpy arrays
    """
    emb_dir = Path(embedding_dir)
    gt_dir = Path(gt_dir)

    if not emb_dir.is_dir():
        raise FileNotFoundError(f"Embedding directory not found: {emb_dir}")
    if not gt_dir.is_dir():
        raise FileNotFoundError(f"Ground truth directory not found: {gt_dir}")

    # Load patient-level split assignments
    with open(split_file_path, "r") as f:
        split_assignments = json.load(f)

    # Build sets of volume names per split
    train_volumes = set(split_assignments["train"])
    val_volumes = set(split_assignments["val"])
    test_volumes = set(split_assignments["test"])

    # Strip .nii.gz/.npy extensions for matching (embeddings are saved by base name)
    def _base_name(v):
        return v.replace(".nii.gz", "").replace(".npy", "")

    train_bases = {_base_name(v) for v in train_volumes}
    val_bases = {_base_name(v) for v in val_volumes}
    test_bases = {_base_name(v) for v in test_volumes}

    # Find matching files
    emb_files = sorted(emb_dir.glob("*.npz"))
    gt_files = sorted(gt_dir.glob("*.npz"))

    emb_names = {f.stem for f in emb_files}
    # Groundtruth files are named like "valid_1001_a_1.nii.gz.npz",
    # so .stem gives "valid_1001_a_1.nii.gz". Strip .nii.gz to match embeddings.
    gt_names = {f.stem.replace(".nii.gz", "") for f in gt_files}
    common = sorted(emb_names & gt_names)

    if not common:
        raise RuntimeError(
            f"No matching files between {emb_dir} and {gt_dir}"
        )

    # Assign each matching volume to its split
    train_names = [n for n in common if n in train_bases]
    val_names = [n for n in common if n in val_bases]
    test_names = [n for n in common if n in test_bases]

    print(f"Found {len(common)} matching volumes")
    print(f"  Train: {len(train_names)} | Val: {len(val_names)} | Test: {len(test_names)}")

    def _load_split(volume_names, split_label):
        """Load embeddings and labels for a list of volume names."""
        all_X = []
        all_y = []

        for name in tqdm(volume_names, desc=f"Loading {split_label} {probe_type} data"):
            emb_data = np.load(str(emb_dir / f"{name}.npz"))
            # Groundtruth files include .nii.gz in the name: "valid_1001_a_1.nii.gz.npz"
            gt_data = np.load(str(gt_dir / f"{name}.nii.gz.npz"))

            if probe_type == "cls":
                X = emb_data["cls"]  # [D, D_emb]
                y = gt_data["cls_labels"]  # [D] or [D, num_classes]
            else:
                X = emb_data["patch"]  # [D, N, D_emb]
                patch_key = f"patch_labels_{model_key}"
                if patch_key in gt_data:
                    y = gt_data[patch_key]
                else:
                    patch_keys = [k for k in gt_data.keys() if k.startswith("patch_labels")]
                    if patch_keys:
                        y = gt_data[patch_keys[0]]
                    else:
                        continue

            # Flatten slice dimension
            if probe_type == "cls":
                X_flat = X.reshape(-1, X.shape[-1])
                if y.ndim == 1:
                    y_flat = y
                else:
                    y_flat = y.reshape(-1, y.shape[-1])
            else:
                # X: [D, N_patches, D_emb] -> [D * N_patches, D_emb]
                X_flat = X.reshape(-1, X.shape[-1])
                # y: [D, num_classes, grid, grid] -> [D * grid * grid, num_classes]
                if y.ndim == 4:
                    # [D, C, G, G] -> [D, G, G, C] -> [D*G*G, C]
                    y_flat = y.transpose(0, 2, 3, 1).reshape(-1, y.shape[1])
                elif y.ndim == 3:
                    # [D, C, N] -> [D*N, C]
                    y_flat = y.transpose(0, 2, 1).reshape(-1, y.shape[1])
                elif y.ndim == 2:
                    y_flat = y.reshape(-1)
                else:
                    y_flat = y.reshape(-1, y.shape[-1])

            # Validate that X and y have matching row counts
            if X_flat.shape[0] != y_flat.shape[0]:
                print(f"  [WARN] {name}: X rows ({X_flat.shape[0]}) != y rows "
                      f"({y_flat.shape[0]}), skipping")
                continue

            all_X.append(X_flat)
            all_y.append(y_flat)

        if not all_X:
            return np.array([]), np.array([])
        return np.concatenate(all_X, axis=0), np.concatenate(all_y, axis=0)

    train_X, train_y = _load_split(train_names, "train")
    val_X, val_y = _load_split(val_names, "val")
    test_X, test_y = _load_split(test_names, "test")

    print(f"Total samples — Train: {train_X.shape[0]}, Val: {val_X.shape[0]}, Test: {test_X.shape[0]}")

    return train_X, train_y, val_X, val_y, test_X, test_y


