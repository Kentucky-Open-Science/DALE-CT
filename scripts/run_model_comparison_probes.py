#!/usr/bin/env python
"""
Model Comparison Study: Unified Linear Probe Training + Visualization.
=====================================================================

Trains simple linear probes (CLS and patch-level) on pre-extracted
embeddings from all 4 backbones, using pre-computed ground truth labels
for ReXGroundingCT or TotalSegmentator.

For each (model, probe_type) combination, runs a grid search over
learning rates, selects the best LR by validation AUPRC (both ReX and
TotalSegmentator use multi-label BCE), and saves results.

After all training completes, generates visualization plots.

Output Structure:
  {save_root}/
    {model_key}/
      {probe_type}/
        best_model.pth
        best_metrics.json
        lr_{lr}/
          model.pth
          metrics.json
    figures/
      macro_auprc_bars.png
      per_class_heatmap.png
      grid_search_heatmaps.png
      summary_table.txt

Usage:
  python scripts/run_model_comparison_probes.py \
      --config configs/linear_probe_model_comparison_rex.yaml

  # Run only specific models
  python scripts/run_model_comparison_probes.py \
      --config configs/linear_probe_model_comparison_rex.yaml \
      --models lejepa_0 lejepa_2s

  # Run only specific probe types
  python scripts/run_model_comparison_probes.py \
      --config configs/linear_probe_model_comparison_rex.yaml \
      --probe-types cls
"""

