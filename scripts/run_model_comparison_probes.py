def save_consolidated_results(all_results, config):
    """
    Save a flat, human-readable JSON with per-class and macro results
    for all (model, probe_type) combinations. This is the primary output
    file for downstream analysis and paper tables.

    Now includes per-class prevalence (train/val/test) and flags for
    classes with insufficient data.
    """
    exp_cfg = config["experiment"]
    task = config["task"]
    task_type = config["task_type"]
    # Resolve class names: rex_classes for ReX, ts_classes for TotalSegmentator
    class_names = config.get("rex_classes", None) or config.get("ts_classes", None)
    min_pos = exp_cfg.get("min_positive_samples", 5)

    save_root = exp_cfg["save_root"]
    os.makedirs(save_root, exist_ok=True)

    # Build a flat list of result entries
    entries = []
    for r in all_results:
        model_key = r["model"]
        probe_type = r["probe_type"]

        # Extract test metrics (preferred) or val metrics
        test_m = r.get("test_metrics", {})
        val_m = r.get("val_detailed_metrics", {})

        entry = {
            "model": model_key,
            "probe_type": probe_type,
            "task": task,
            "task_type": task_type,
            "best_lr": r["best_lr"],
            "best_val_metric": r["best_val_metric"],
            "n_train": r.get("n_train", 0),
            "n_val": r.get("n_val", 0),
            "n_test": r.get("n_test", 0),
            "min_positive_samples": min_pos,
        }

        if task_type == "multi_label":
            entry["test_macro_auroc"] = test_m.get("macro_auroc", None)
            entry["test_macro_auprc"] = test_m.get("macro_auprc", None)
            entry["test_macro_auroc_unfiltered"] = test_m.get("macro_auroc_unfiltered", None)
            entry["test_macro_auprc_unfiltered"] = test_m.get("macro_auprc_unfiltered", None)
            entry["test_n_valid_classes"] = test_m.get("n_valid_classes", None)
            entry["test_n_total_classes"] = test_m.get("n_total_classes", None)
            entry["test_n_skipped_classes"] = test_m.get("n_skipped_classes", None)
            entry["val_macro_auroc"] = val_m.get("macro_auroc", None)
            entry["val_macro_auprc"] = val_m.get("macro_auprc", None)
            entry["val_macro_auroc_unfiltered"] = val_m.get("macro_auroc_unfiltered", None)
            entry["val_macro_auprc_unfiltered"] = val_m.get("macro_auprc_unfiltered", None)
            entry["val_n_valid_classes"] = val_m.get("n_valid_classes", None)
            entry["val_n_total_classes"] = val_m.get("n_total_classes", None)
            entry["val_n_skipped_classes"] = val_m.get("n_skipped_classes", None)

            # Per-class metrics with prevalence (test preferred, fall back to val)
            test_per_class = test_m.get("per_class", {})
            val_per_class = val_m.get("per_class", {})
            per_class = {}
            if class_names:
                for cls_name in class_names:
                    tc = test_per_class.get(cls_name, {})
                    vc = val_per_class.get(cls_name, {})
                    # Use test if available, else val
                    source = tc if tc else vc
                    per_class[cls_name] = {
                        "test_auroc": tc.get("auroc", None),
                        "test_auprc": tc.get("auprc", None),
                        "val_auroc": vc.get("auroc", None),
                        "val_auprc": vc.get("auprc", None),
                        "train_prevalence": source.get("train_prevalence", None),
                        "val_prevalence": source.get("val_prevalence", None),
                        "test_prevalence": source.get("eval_prevalence", None),
                        "test_positive_count": source.get("eval_positive_count", None),
                        "sufficient_data": source.get("sufficient_data", None),
                        "skipped_reason": source.get("skipped_reason", None),
                    }
            else:
                # Fallback: use whatever keys are in per_class
                source = test_per_class if test_per_class else val_per_class
                for cls_name, metrics in source.items():
                    tc = test_per_class.get(cls_name, {})
                    vc = val_per_class.get(cls_name, {})
                    per_class[cls_name] = {
                        "test_auroc": tc.get("auroc", None),
                        "test_auprc": tc.get("auprc", None),
                        "val_auroc": vc.get("auroc", None),
                        "val_auprc": vc.get("auprc", None),
                        "train_prevalence": metrics.get("train_prevalence", None),
                        "val_prevalence": metrics.get("val_prevalence", None),
                        "test_prevalence": metrics.get("eval_prevalence", None),
                        "test_positive_count": metrics.get("eval_positive_count", None),
                        "sufficient_data": metrics.get("sufficient_data", None),
                        "skipped_reason": metrics.get("skipped_reason", None),
                    }
            entry["per_class"] = per_class
        else:
            entry["test_accuracy"] = test_m.get("accuracy", None)
            entry["val_accuracy"] = val_m.get("accuracy", None)

        entries.append(entry)

    # Save consolidated JSON
    consolidated = {
        "task": task,
        "task_type": task_type,
        "num_classes": config.get("num_classes", None),
        "embedding_method": config["embeddings"]["method"],
        "min_positive_samples": min_pos,
        "results": entries,
    }

    output_path = os.path.join(save_root, "consolidated_results.json")
    with open(output_path, "w") as f:
        json.dump(consolidated, f, indent=2, default=str)
    print(f"\n✅ Consolidated results saved to: {output_path}")


